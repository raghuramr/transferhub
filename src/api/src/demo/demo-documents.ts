import PDFDocument = require('pdfkit');

/**
 * Renders the sample documents a student would upload (transcript, ID / passport, English test, syllabus, enrolment
 * letter) as realistic-looking PDFs: institution letterhead with a crest in a colour derived from its code, tables,
 * seals and signatures, an ID card, a passport data page with a valid machine-readable zone, score reports with bars.
 * Pure functions: callers pass plain data, so the same renderers serve the super-admin "Demo documents" tool and the
 * offline sample-pack script. Every page keeps a real text layer laid out so the Smart Upload rules reader classifies and
 * reads it (term headings, "CODE Title credits grade" rows, labelled fields, "Course Description" / "Topics Covered"
 * headings, MRZ lines) - checked in scripts/test-demo-documents.ts.
 */

export type DemoDocKind = 'transcript' | 'id_document' | 'english_test' | 'syllabus' | 'enrollment_letter';
export const DEMO_DOC_KINDS: { kind: DemoDocKind; label: string }[] = [
  { kind: 'transcript', label: 'Transcript (one per previous college)' },
  { kind: 'id_document', label: 'ID / passport copy' },
  { kind: 'english_test', label: 'English test report (international students)' },
  { kind: 'syllabus', label: 'Course syllabi (one per course)' },
  { kind: 'enrollment_letter', label: 'Enrolment verification letter' },
];

