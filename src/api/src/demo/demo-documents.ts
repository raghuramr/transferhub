function avatar(d: Doc, x: number, y: number, w: number, h: number, color: string) {
  d.save();
  d.rect(x, y, w, h).fillAndStroke('#e7ebf0', LINE);
  d.rect(x, y, w, h).clip();
  d.circle(x + w / 2, y + h * 0.38, w * 0.2).fill(color);
  d.ellipse(x + w / 2, y + h * 0.92, w * 0.38, h * 0.32).fill(color);
  d.restore();
}

const COUNTRY3: Record<string, string> = {
  india: 'IND', kenya: 'KEN', poland: 'POL', colombia: 'COL', philippines: 'PHL', turkey: 'TUR', vietnam: 'VNM', nigeria: 'NGA', 'south korea': 'KOR', germany: 'DEU',
  china: 'CHN', brazil: 'BRA', egypt: 'EGY', canada: 'CAN', japan: 'JPN', bangladesh: 'BGD', mexico: 'MEX', 'united states': 'USA', france: 'FRA', 'united kingdom': 'GBR',
};
const country3 = (c: string) => COUNTRY3[c.trim().toLowerCase()] ?? c.replace(/[^a-z]/gi, '').slice(0, 3).toUpperCase().padEnd(3, 'X');
const mrzCheck = (s: string) => {
  const w = [7, 3, 1];
  let sum = 0;
  for (let i = 0; i < s.length; i++) { const ch = s[i]; const v = ch === '<' ? 0 : /\d/.test(ch) ? +ch : ch.charCodeAt(0) - 55; sum += v * w[i % 3]; }
  return String(sum % 10);
};
const yymmdd = (iso: string) => iso.slice(2, 4) + iso.slice(5, 7) + iso.slice(8, 10);
const mz = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]+/g, '<');

/** Two valid TD3 machine-readable lines for the passport. */
export function mrzLines(s: DocStudent, expiryIso: string): [string, string] {
  const c3 = country3(s.country);
  const l1 = (`P<${c3}${mz(s.lastName)}<<${mz(s.firstName)}`).padEnd(44, '<').slice(0, 44);
  const no = mz(s.studentId).padEnd(9, '<').slice(0, 9);
  const dob = yymmdd(s.dateOfBirth), exp = yymmdd(expiryIso);
  const body = `${no}${mrzCheck(no)}${c3}${dob}${mrzCheck(dob)}<${exp}${mrzCheck(exp)}${'<'.repeat(14)}0`;
  const comp = mrzCheck(body.slice(0, 10) + body.slice(13, 20) + body.slice(21, 43));
  return [l1, (body + comp).slice(0, 44)];
}

