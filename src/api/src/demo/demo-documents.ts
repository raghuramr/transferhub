export function transcriptPdf(s: DocStudent, inst: DocInstitution, courses: DocCourse[]): Promise<Buffer> {
  const b = brand(inst);
  return pdf(`${inst.name} transcript`, inst.name, (d) => {
    let y = letterhead(d, inst, 'Office of the Registrar  ·  Official Academic Transcript');
    d.font('Helvetica-Bold').fontSize(8).fillColor(MUTED).text(`Document no. ${docNo(inst, s, 'TR')}`, M, y - 6, { width: CONTENT_W, align: 'right', lineBreak: false });
    const info: [string, string][] = [
      ['Student', `${s.firstName} ${s.lastName}`], ['Student ID', s.studentId], ['Date of birth', s.dateOfBirth],
      ['Calendar', inst.calendar === 'quarter' ? 'Quarter' : 'Semester'], ['Level', 'Undergraduate'], ['Issued', fmtDate('2026-10-01')],
    ];
    if (s.program) info.splice(3, 0, ['Program', s.program]);
    if (inst.school) info.push(['School', inst.school]);
    y = infoBox(d, inst, info, y + 4);

    const cols = { code: M + 6, title: M + 86, cr: M + 330, gr: M + 380, pts: M + 430 };
    const head = (yy: number) => {
      d.rect(M, yy, CONTENT_W, 20).fill(b.primary);
      d.fillColor('#ffffff').font('Helvetica-Bold').fontSize(8.5);
      d.text('Code', cols.code, yy + 6, { lineBreak: false }); d.text('Course title', cols.title, yy + 6, { lineBreak: false });
      d.text('Credits', cols.cr, yy + 6, { lineBreak: false }); d.text('Grade', cols.gr, yy + 6, { lineBreak: false }); d.text('Points', cols.pts, yy + 6, { lineBreak: false });
      d.fillColor(INK);
      return yy + 22;
    };
    y = head(y);
    let credits = 0, pts = 0, graded = 0, n = 0;
    const terms = [...new Set(courses.map((c) => c.term))];
    for (const t of terms) {
      if (y > 660) { d.addPage(); y = head(60); }
      d.rect(M, y, CONTENT_W, 17).fill(b.tint);
      d.fillColor(b.primary).font('Helvetica-Bold').fontSize(9).text(t, cols.code, y + 4.5, { lineBreak: false });
      d.fillColor(INK);
      y += 19;
      let termCredits = 0, termPts = 0, termGraded = 0;
      for (const c of courses.filter((x) => x.term === t)) {
        if (y > 700) { d.addPage(); y = head(60); }
        const gp = GP[c.grade];
        if (n % 2) d.rect(M, y - 2, CONTENT_W, 16).fill('#fafbfc');
        d.fillColor(INK).font('Helvetica').fontSize(9);
        d.text(c.code, cols.code, y + 1, { width: 76, lineBreak: false });
        d.text(c.title, cols.title, y + 1, { width: 236, lineBreak: false, ellipsis: true });
        d.text(String(c.credits), cols.cr, y + 1, { lineBreak: false });
        d.font('Helvetica-Bold').text(c.grade, cols.gr, y + 1, { lineBreak: false });
        d.font('Helvetica').text(gp === undefined ? '-' : (gp * c.credits).toFixed(1), cols.pts, y + 1, { lineBreak: false });
        d.moveTo(M, y + 14).lineTo(M + CONTENT_W, y + 14).lineWidth(0.4).strokeColor(LINE).stroke();
        credits += c.credits; termCredits += c.credits; n++;
        if (gp !== undefined) { pts += gp * c.credits; graded += c.credits; termPts += gp * c.credits; termGraded += c.credits; }
        y += 16;
      }
      d.font('Helvetica-Oblique').fontSize(8).fillColor(MUTED).text(`Term credits ${termCredits}   Term GPA ${(termGraded ? termPts / termGraded : 0).toFixed(2)}`, M + 6, y, { width: CONTENT_W - 12, align: 'right', lineBreak: false });
      d.fillColor(INK);
      y += 14;
    }
    if (y > 600) { d.addPage(); y = 70; }
    y += 6;
    d.roundedRect(M, y, CONTENT_W, 46, 4).lineWidth(1).strokeColor(b.primary).stroke();
    d.font('Helvetica-Bold').fontSize(10).fillColor(INK).text(`Credits completed: ${credits}`, M + 14, y + 10, { lineBreak: false });
    d.text(`Cumulative GPA: ${(graded ? pts / graded : 0).toFixed(2)}`, M + 200, y + 10, { lineBreak: false });
    d.font('Helvetica').fontSize(8.5).fillColor(MUTED).text('Grading scale: A 4.00, A- 3.67, B+ 3.33, B 3.00, B- 2.67, C+ 2.33, C 2.00, C- 1.67, D 1.00, F 0.00, P = pass (not in GPA).', M + 14, y + 28, { width: CONTENT_W - 28, lineBreak: false });
    y += 70;
    signature(d, inst, M, y, 'University Registrar');
    seal(d, M + CONTENT_W - 60, y + 22, inst, 'Official');
    d.font('Helvetica-Bold').fontSize(7).fillColor(MUTED).text('END OF TRANSCRIPT', M, y + 78, { width: CONTENT_W, align: 'center', lineBreak: false });
  });
}

