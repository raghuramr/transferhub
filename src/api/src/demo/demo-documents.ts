const MUTED = '#5f6672';
const LINE = '#d9dde3';
const PAGE_W = 612;
const M = 54; // margin
const CONTENT_W = PAGE_W - M * 2;
const GP: Record<string, number> = { 'A+': 4, A: 4, 'A-': 3.67, 'B+': 3.33, B: 3, 'B-': 2.67, 'C+': 2.33, C: 2, 'C-': 1.67, 'D+': 1.33, D: 1, F: 0 };

const hashOf = (s: string) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; };
const PALETTE = [
  { primary: '#7a1424', tint: '#f6e9ec' }, { primary: '#12395f', tint: '#e8eff6' }, { primary: '#1d5c46', tint: '#e7f3ee' },
  { primary: '#4a2a73', tint: '#efe9f6' }, { primary: '#8a4b0f', tint: '#f8eee2' }, { primary: '#0f5560', tint: '#e5f2f4' },
];
const brand = (inst: DocInstitution) => PALETTE[hashOf(inst.code || inst.name) % PALETTE.length];
const initials = (name: string) => {
  const w = name.replace(/\b(of|the|and|at)\b/gi, '').split(/\s+/).filter(Boolean);
  return (w.length > 1 ? w.slice(0, 3).map((x) => x[0]).join('') : name.slice(0, 2)).toUpperCase();
};
const slug = (s: string) => s.normalize('NFD').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase();
/** File-name-safe text that keeps spaces and accents readable ("Maya Rivera"). */
export const safeName = (s: string) => s.replace(/[\\/:*?"<>|\u0000-\u001f]+/g, '').replace(/\s+/g, ' ').trim();
const fmtDate = (iso: string) => {
  const d = new Date(iso + 'T00:00:00Z');
  return Number.isNaN(+d) ? iso : d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });
};

const FOOTER = 'Synthetic sample document generated by TransferHub for testing. Not an official record.';

function pdf(title: string, author: string, draw: (d: Doc) => void, footer = FOOTER): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'LETTER', margin: M, bufferPages: true, info: { Title: title, Author: author, Producer: 'TransferHub demo documents', CreationDate: new Date('2026-10-01T00:00:00Z') } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    draw(doc);
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.page.margins.bottom = 0; // allow drawing in the bottom margin without triggering a new page
      doc.font('Helvetica').fontSize(7).fillColor(MUTED).text(`${footer}   Page ${i + 1} of ${range.count}`, M, 756, { width: CONTENT_W, align: 'center', lineBreak: false });
    }
    doc.end();
  });
}

/** Crest: ring + monogram in the institution colour. */
function crest(d: Doc, cx: number, cy: number, r: number, inst: DocInstitution, onDark = true) {
  const b = brand(inst);
  d.save();
  d.circle(cx, cy, r).fillAndStroke(onDark ? '#ffffff' : b.primary, onDark ? '#ffffff' : b.primary);
  d.circle(cx, cy, r - 3).lineWidth(1).stroke(onDark ? b.primary : '#ffffff');
  d.fillColor(onDark ? b.primary : '#ffffff').font('Times-Bold').fontSize(r * 0.7).text(initials(inst.name).slice(0, 3), cx - r, cy - r * 0.34, { width: r * 2, align: 'center', lineBreak: false });
  d.restore();
}

/** Coloured letterhead band across the top of page 1. Returns the y where content can start. */
function letterhead(d: Doc, inst: DocInstitution, officeText: string): number {
  const b = brand(inst);
  const office = inst.school ? `${officeText}  ·  ${inst.school}` : officeText;
  d.rect(0, 0, PAGE_W, 92).fill(b.primary);
  d.rect(0, 92, PAGE_W, 3).fill('#c9a24a');
  crest(d, M + 24, 46, 24, inst);
  d.fillColor('#ffffff').font('Times-Bold').fontSize(20).text(inst.name, M + 62, 28, { width: CONTENT_W - 62, lineBreak: false });
  d.font('Helvetica').fontSize(9).fillColor('#f1e3e6').text(office, M + 62, 54, { width: CONTENT_W - 62, lineBreak: false });
  d.fontSize(8).text(`www.${slug(inst.code)}.example.edu`, M + 62, 68, { width: CONTENT_W - 62, lineBreak: false });
  d.fillColor(INK);
  return 116;
}

function sectionTitle(d: Doc, inst: DocInstitution, text: string, y: number): number {
  const b = brand(inst);
  d.font('Helvetica-Bold').fontSize(9).fillColor(b.primary).text(text.toUpperCase(), M, y, { width: CONTENT_W, characterSpacing: 0.8, lineBreak: false });
  d.moveTo(M, y + 13).lineTo(M + CONTENT_W, y + 13).lineWidth(0.8).strokeColor(b.primary).stroke();
  d.fillColor(INK);
  return y + 20;
}

/** Two-column grid of "Label: value" cells inside a light bordered box. Returns the y below the box. */
function infoBox(d: Doc, inst: DocInstitution, rows: [string, string][], y: number): number {
  const b = brand(inst);
  const perCol = Math.ceil(rows.length / 2);
  const h = perCol * 17 + 14;
  d.roundedRect(M, y, CONTENT_W, h, 4).fillAndStroke(b.tint, LINE);
  rows.forEach(([k, v], i) => {
    const col = i < perCol ? 0 : 1;
    const row = i % perCol;
    const x = M + 12 + col * (CONTENT_W / 2);
    const yy = y + 8 + row * 17;
    d.font('Helvetica-Bold').fontSize(9).fillColor(MUTED).text(`${k}: `, x, yy, { continued: true, lineBreak: false });
    d.font('Helvetica').fillColor(INK).text(v || '-', { lineBreak: false, width: CONTENT_W / 2 - 80 });
  });
  return y + h + 14;
}

/** Official-looking round seal. */
function seal(d: Doc, cx: number, cy: number, inst: DocInstitution, label: string) {
  const b = brand(inst);
  d.save();
  d.circle(cx, cy, 36).lineWidth(2).strokeColor(b.primary).stroke();
  d.circle(cx, cy, 31).lineWidth(0.7).stroke();
  d.circle(cx, cy, 18).lineWidth(0.7).stroke();
  d.fillColor(b.primary).font('Times-Bold').fontSize(13).text(initials(inst.name).slice(0, 3), cx - 18, cy - 7, { width: 36, align: 'center', lineBreak: false });
  d.font('Helvetica-Bold').fontSize(5.5).text(label.toUpperCase(), cx - 31, cy + 20, { width: 62, align: 'center', lineBreak: false });
  d.font('Helvetica-Bold').fontSize(5.5).text(inst.name.toUpperCase().slice(0, 28), cx - 31, cy - 28, { width: 62, align: 'center', lineBreak: false });
  d.restore();
}

