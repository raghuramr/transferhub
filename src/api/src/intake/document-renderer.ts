import PDFDocument from 'pdfkit';
import type { SourceCourse, SourceProfile } from './source-connector';

const INK = '#1f1a1b';
const MUTED = '#6b5f61';
const BRAND = '#770816';

function toBuffer(build: (doc: PDFKit.PDFDocument) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'LETTER', margin: 50, info: { Title: 'Student record', Producer: 'TransferHub' } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    build(doc);
    doc.end();
  });
}

const fmtDate = (d: Date | null) => (d ? new Date(d).toISOString().slice(0, 10) : '-');

function header(doc: PDFKit.PDFDocument, p: SourceProfile, title: string) {
  doc.fillColor(BRAND).font('Helvetica-Bold').fontSize(18).text(p.institutionName, { align: 'left' });
  doc.fillColor(MUTED).font('Helvetica').fontSize(10).text(`${p.institutionCode}  |  ${p.sourceSystem}`);
  doc.moveDown(0.6);
  doc.moveTo(50, doc.y).lineTo(562, doc.y).strokeColor(BRAND).lineWidth(1.5).stroke();
  doc.moveDown(0.8);
  doc.fillColor(INK).font('Helvetica-Bold').fontSize(14).text(title);
  doc.moveDown(0.5);
}

function labelled(doc: PDFKit.PDFDocument, rows: [string, string][]) {
  doc.fontSize(10);
  for (const [k, v] of rows) {
    doc.font('Helvetica-Bold').fillColor(MUTED).text(`${k}: `, { continued: true });
    doc.font('Helvetica').fillColor(INK).text(v || '-');
  }
}

/** A clean, official-looking transcript generated from the structured record. */
export function renderTranscript(p: SourceProfile, courses: SourceCourse[]): Promise<Buffer> {
  return toBuffer((doc) => {
    header(doc, p, 'Academic Transcript');
    labelled(doc, [
      ['Student', `${p.firstName} ${p.lastName}`],
      ['Student ID', p.externalId],
      ['Date of birth', fmtDate(p.dateOfBirth)],
      ['Program', [p.programName, p.degree].filter(Boolean).join(' - ')],
      ['Field of study', p.fieldOfStudy ?? ''],
    ]);
    doc.moveDown(0.8);

    const cols = [50, 140, 400, 470, 520];
    const rowH = 18;
    let y = doc.y;
    doc.rect(50, y - 3, 512, rowH).fill('#f3e8ea');
    doc.fillColor(INK).font('Helvetica-Bold').fontSize(9);
    ['Code', 'Title', 'Term', 'Credits', 'Grade'].forEach((h, i) => doc.text(h, cols[i] + 4, y + 2, { width: (cols[i + 1] ?? 562) - cols[i] - 6 }));
    y += rowH;
    doc.font('Helvetica').fontSize(9);

    let total = 0;
    let points = 0;
    const GP: Record<string, number> = { 'A+': 4, A: 4, 'A-': 3.7, 'B+': 3.3, B: 3, 'B-': 2.7, 'C+': 2.3, C: 2, 'C-': 1.7, 'D+': 1.3, D: 1, F: 0 };
    for (const c of courses) {
      if (y > 700) {
        doc.addPage();
        y = 60;
      }
      doc.fillColor(INK);
      doc.text(c.courseCode, cols[0] + 4, y, { width: cols[1] - cols[0] - 6, lineBreak: false });
      doc.text(c.courseTitle, cols[1] + 4, y, { width: cols[2] - cols[1] - 6, lineBreak: false, ellipsis: true });
      doc.text(c.term ?? '-', cols[2] + 4, y, { width: cols[3] - cols[2] - 6, lineBreak: false });
      doc.text(c.credits.toFixed(1), cols[3] + 4, y, { width: cols[4] - cols[3] - 6, lineBreak: false });
      doc.text(c.grade, cols[4] + 4, y, { width: 40, lineBreak: false });
      doc.moveTo(50, y + 13).lineTo(562, y + 13).strokeColor('#eadcde').lineWidth(0.5).stroke();
      total += c.credits;
      if (GP[c.grade] !== undefined) points += GP[c.grade] * c.credits;
      y += rowH;
    }
    doc.y = y + 8;
    doc.x = 50;
    const gpa = p.gpa ?? (total ? points / total : 0);
    doc.font('Helvetica-Bold').fontSize(10).fillColor(INK).text(`Total credits: ${total.toFixed(1)}    Cumulative GPA: ${gpa.toFixed(2)}`, 50, doc.y);
    doc.moveDown(1.5);
    doc.font('Helvetica-Oblique').fontSize(8).fillColor(MUTED).text(
      `Generated by TransferHub from the record held by ${p.sourceSystem}${p.isMock ? ' (sample data for demonstration)' : ''}. Issued ${fmtDate(new Date())}.`,
      50,
      doc.y,
      { width: 512 },
    );
  });
}

/** A simple identity / enrolment summary page. */
export function renderIdDocument(p: SourceProfile): Promise<Buffer> {
  return toBuffer((doc) => {
    header(doc, p, 'Student Identification Summary');
    labelled(doc, [
      ['Name', `${p.firstName} ${p.lastName}`],
      [p.idType === 'passport' ? 'Passport number' : 'Student ID', p.externalId],
      ['Date of birth', fmtDate(p.dateOfBirth)],
      ['Email', p.email],
      ['Phone', p.phone ?? ''],
      ['Country', p.country ?? ''],
      ['Country of origin', p.countryOfOrigin ?? ''],
      ['City / state', [p.city, p.state].filter(Boolean).join(', ')],
      ['Program', [p.programName, p.degree].filter(Boolean).join(' - ')],
      ['Expected graduation', p.graduationYear ? String(p.graduationYear) : ''],
    ]);
    doc.moveDown(1.5);
    doc.font('Helvetica-Oblique').fontSize(8).fillColor(MUTED).text(
      `Generated by TransferHub from the record held by ${p.sourceSystem}${p.isMock ? ' (sample data for demonstration)' : ''}.`,
      50,
      doc.y,
      { width: 512 },
    );
  });
}
