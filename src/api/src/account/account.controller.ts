import {
  BadRequestException, Body, Controller, Delete, Get, NotFoundException, Param, Post, Put, Req, Res,
  UploadedFile, UseGuards, UseInterceptors,
} from '@nestjs/common';
import { FileInterceptor } from '@nestjs/platform-express';
import { IsEmail, IsInt, IsOptional, IsString, MinLength } from 'class-validator';
import type { Response } from 'express';
import { AccountService } from './account.service';
import { JwtAuthGuard } from '../auth/jwt-auth.guard';
import { RolesGuard } from '../auth/roles.guard';
import { Roles } from '../auth/roles.decorator';
import type { AuthenticatedRequest } from '../auth/authenticated-request.interface';
import type { UploadedFileLike } from '../common/uploaded-file.interface';

class RequestEmailChangeDto {
  @IsEmail() newEmail: string;
  @IsString() @MinLength(1) password: string;
}
class SetTargetDto {
  @IsInt() institutionId: number;
  @IsOptional() @IsInt() programId?: number;
}
class UpdateStudentProfileDto {
  @IsOptional() @IsString() currentInstitution?: string;
  @IsOptional() @IsString() currentProgram?: string;
}
class ConfirmEmailChangeDto {
  @IsString() @MinLength(20) token: string;
}

const PHOTO_TYPES = ['image/jpeg', 'image/png', 'image/webp'];

@Controller('account')
export class AccountController {
  constructor(private account: AccountService) {}

  @Post('email-change')
  @UseGuards(JwtAuthGuard)
  requestEmailChange(@Body() dto: RequestEmailChangeDto, @Req() req: AuthenticatedRequest) {
    return this.account.requestEmailChange(req.user, dto.newEmail, dto.password);
  }

  /** Public: the emailed token is the credential. */
  @Post('email-change/confirm')
  confirmEmailChange(@Body() dto: ConfirmEmailChangeDto) {
    return this.account.confirmEmailChange(dto.token);
  }

  /** Selectable receiving universities with their active programs (profile + Explore). */
  @Get('targets')
  @UseGuards(JwtAuthGuard, RolesGuard)
  @Roles('student')
  targets() {
    return this.account.getTargets();
  }

  /** The student's own target; existing requests are never changed. */
  @Put('target')
  @UseGuards(JwtAuthGuard, RolesGuard)
  @Roles('student')
  setTarget(@Body() dto: SetTargetDto, @Req() req: AuthenticatedRequest) {
    return this.account.setTarget(req.user, dto.institutionId, dto.programId ?? null);
  }

  @Get('student-overview')
  @UseGuards(JwtAuthGuard, RolesGuard)
  @Roles('student')
  overview(@Req() req: AuthenticatedRequest) {
    return this.account.studentOverview(req.user.id);
  }

  /** Student edits their own current institution / program (free text). */
  @Put('student-profile')
  @UseGuards(JwtAuthGuard, RolesGuard)
  @Roles('student')
  updateStudentProfile(@Body() dto: UpdateStudentProfileDto, @Req() req: AuthenticatedRequest) {
    return this.account.updateStudentProfile(req.user, dto);
  }

  @Put('photo')
  @UseGuards(JwtAuthGuard)
  @UseInterceptors(
    FileInterceptor('file', {
      limits: { fileSize: 5 * 1024 * 1024, files: 1 },
      fileFilter: (_req, file, cb) =>
        PHOTO_TYPES.includes(file.mimetype) ? cb(null, true) : cb(new BadRequestException('Use a JPG, PNG or WebP image.'), false),
    }),
  )
  setPhoto(@UploadedFile() file: UploadedFileLike, @Req() req: AuthenticatedRequest) {
    if (!file) throw new BadRequestException('No image uploaded');
    return this.account.setPhoto(req.user, file);
  }

  @Delete('photo')
  @UseGuards(JwtAuthGuard)
  removePhoto(@Req() req: AuthenticatedRequest) {
    return this.account.removePhoto(req.user.id);
  }

  /** Admin (or self) uploads a photo for a specific user — replaces any generated initials avatar. */
  @Put('photo/:userId')
  @UseGuards(JwtAuthGuard)
  @UseInterceptors(
    FileInterceptor('file', {
      limits: { fileSize: 5 * 1024 * 1024, files: 1 },
      fileFilter: (_req, file, cb) =>
        PHOTO_TYPES.includes(file.mimetype) ? cb(null, true) : cb(new BadRequestException('Use a JPG, PNG or WebP image.'), false),
    }),
  )
  setPhotoForUser(@Param('userId') userId: string, @UploadedFile() file: UploadedFileLike, @Req() req: AuthenticatedRequest) {
    if (!file) throw new BadRequestException('No image uploaded');
    return this.account.setPhotoForUser(userId, req.user, file);
  }

  @Delete('photo/:userId')
  @UseGuards(JwtAuthGuard)
  removePhotoForUser(@Param('userId') userId: string, @Req() req: AuthenticatedRequest) {
    return this.account.removePhotoFor(userId, req.user);
  }

  /** Default profile picture = the logo; this clears initials avatars generated by an earlier version. */
  @Post('photos/reset-defaults')
  @UseGuards(JwtAuthGuard, RolesGuard)
  @Roles('super_admin')
  resetDefaults() {
    return this.account.resetDefaultPhotos();
  }

  /** Any signed-in user may view any profile photo (shown beside names across the app). */
  @Get('photo/:userId')
  @UseGuards(JwtAuthGuard)
  async photo(@Param('userId') userId: string, @Res() res: Response) {
    const photo = await this.account.openPhoto(userId);
    if (!photo) throw new NotFoundException('No photo');
    res.setHeader('Content-Type', photo.mimeType);
    res.setHeader('Cache-Control', 'private, max-age=300');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    res.setHeader('Content-Security-Policy', "default-src 'none'; style-src 'unsafe-inline'; sandbox");
    photo.stream.on('error', () => res.destroy());
    photo.stream.pipe(res);
  }
}
