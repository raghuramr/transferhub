#!/usr/bin/env node
// Generates <set>/postman.collection.json from the set's catalogue.json and students files
// so they cannot drift. Usage: node docs/demo-data/tools/build-postman.js <set-folder>
const fs = require('fs');
const path = require('path');

const dir = path.resolve(process.argv[2] || '.');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'catalogue.json'), 'utf8'));
const SET = JSON.parse(fs.readFileSync(path.join(dir, 'set.json'), 'utf8'));
const CODE = SET.universityCode;
const UNI = SET.universityName;
const studentsNoDocs = JSON.parse(fs.readFileSync(path.join(dir, 'students-no-documents.json'), 'utf8'));
const nStudents = studentsNoDocs.students.length;
const nCourses = data.courses.length;
const nStudentCourses = studentsNoDocs.students.reduce((n, s) => n + s.courses.length, 0);
const nDocs = JSON.parse(fs.readFileSync(path.join(dir, 'students.json'), 'utf8')).students.reduce((n, s) => n + s.documents.length, 0);
const folder = path.basename(dir);
const quick = Math.min(5, nStudents);

const postTestLines = [
  'let body = {};',
  'try { body = pm.response.json(); } catch (e) {}',
  'pm.test("Accepted (HTTP 2xx)", function () { pm.response.to.be.success; });',
  'if (body.reference) {',
  '  pm.collectionVariables.set("reference", body.reference);',
  '  console.log("Reference saved: " + body.reference);',
  '}',
  'if (body.validation) {',
  '  const v = body.validation;',
  '  console.log("Validation - valid: " + JSON.stringify(v.valid) + ", warnings: " + JSON.stringify(v.warnings) + ", errors: " + JSON.stringify(v.errors));',
  '}',
  'console.log("Status: " + body.status + ", rows received: " + JSON.stringify(body.received));',
];

const url = (p) => ({
  raw: '{{baseUrl}}' + p,
  host: ['{{baseUrl}}'],
  path: p.split('/').filter(Boolean),
});
const keyHeader = { key: 'X-API-Key', value: '{{apiKey}}' };
const json = (o) => JSON.stringify(o, null, 2);

const get = (name, p, withKey, description) => ({
  name,
  request: { method: 'GET', header: withKey ? [keyHeader] : [], url: url(p), description },
});
const post = (name, payload, description) => ({
  name,
  event: [{ listen: 'test', script: { type: 'text/javascript', exec: postTestLines } }],
  request: {
    method: 'POST',
    header: [keyHeader, { key: 'Content-Type', value: 'application/json' }],
    body: { mode: 'raw', raw: json(payload), options: { raw: { language: 'json' } } },
    url: url('/api/public/v1/submissions'),
    description,
  },
});

// Same endpoint, but the body is a file chosen in Postman (the version with documents is 240 KB of base64).
const postFile = (name, fileName, description) => ({
  name,
  event: [{ listen: 'test', script: { type: 'text/javascript', exec: postTestLines } }],
  request: {
    method: 'POST',
    header: [keyHeader, { key: 'Content-Type', value: 'application/json' }],
    body: { mode: 'file', file: { src: fileName } },
    url: url('/api/public/v1/submissions'),
    description,
  },
});

const collection = {
  info: {
    name: `TransferHub Partner API - ${UNI} (${CODE})`,
    description: `Generated by docs/demo-data/tools/build-postman.js from ${folder}/catalogue.json. Set the apiKey collection variable to the partner key issued for university code ${CODE}.`,
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [
    { key: 'baseUrl', value: 'https://transferhub.wcubeprojects.in' },
    { key: 'apiKey', value: 'th_live_PASTE_YOUR_KEY' },
    { key: 'reference', value: '' },
  ],
  item: [
    get('Format guide (no key)', '/api/public/v1/format', false, 'Field reference for every entity type. No API key needed.'),
    get('Who am I (check key)', '/api/public/v1/me', true, 'Confirms the key works and shows the university it is scoped to.'),
    post(`POST full catalogue (1 university, ${data.programs.length} programs, ${nCourses} courses)`, data, 'Everything in one submission.'),
    {
      name: 'Step by step',
      item: [
        post('1 University only', { note: 'Step 1 - university', universities: data.universities }, 'Step 1 of the staged demo.'),
        post('2 Programs only', { note: 'Step 2 - programs', programs: data.programs }, `Step 2. Programs reference the university code ${CODE}.`),
        post('3 Courses with topics only', { note: 'Step 3 - courses with topics', courses: data.courses }, 'Step 3. Courses link to programs by programName and carry syllabus topics.'),
      ],
    },
    {
      name: 'Students',
      description: `Student profiles for ${UNI}. Nothing creates an account: approved profiles become "ready to claim" on the student intake page.`,
      item: [
        post(`Students - first ${quick} (quick demo)`, { note: `Student profiles - first ${quick}`, students: studentsNoDocs.students.slice(0, quick) }, `${quick} students with every profile field and their course history, no documents.`),
        post(`Students - all ${nStudents} (no documents)`, studentsNoDocs, `${nStudents} students, ${nStudentCourses} courses. Every profile field filled; courses come from the ${CODE} catalogue.`),
        postFile(`Students - all ${nStudents} WITH documents (choose file)`, 'students.json', `In Postman: Body > pick docs/demo-data/${folder}/students.json. ${nDocs} small PDFs (transcript, ID/passport, English test for international students). Well under the 6 MB limit.`),
      ],
    },
    get('List my submissions', '/api/public/v1/submissions', true, 'All submissions made with this key.'),
    get('Submission detail (per-row outcome)', '/api/public/v1/submissions/{{reference}}', true, 'Uses the reference saved by the last POST.'),
  ],
};

const out = path.join(dir, 'postman.collection.json');
fs.writeFileSync(out, JSON.stringify(collection, null, 2) + '\n');
JSON.parse(fs.readFileSync(out, 'utf8'));
console.log('Wrote ' + path.basename(out) + ' (' + collection.item.length + ' top-level items)');
