#!/usr/bin/env node
// Generates TransferHub-Partner-API.postman_collection.json from pacific-ridge-catalogue.json
// so the two cannot drift. Usage: node docs/demo-data/build-postman.js
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const data = JSON.parse(fs.readFileSync(path.join(dir, 'pacific-ridge-catalogue.json'), 'utf8'));

const postTestLines = [
  'let body = {};',
  'try { body = pm.response.json(); } catch (e) {}',
  'pm.test("Accepted (HTTP 2xx)", function () { pm.response.to.be.success; });',
  'if (body.reference) {',
  '  pm.collectionVariables.set("reference", body.reference);',
  '  console.log("Reference saved: " + body.reference);',
  '}',
  'if (body.validation) {',
  '  const v = body.validation;',
  '  console.log("Validation - valid: " + JSON.stringify(v.valid) + ", warnings: " + JSON.stringify(v.warnings) + ", errors: " + JSON.stringify(v.errors));',
  '}',
  'console.log("Status: " + body.status + ", rows received: " + JSON.stringify(body.received));',
];

const url = (p) => ({
  raw: '{{baseUrl}}' + p,
  host: ['{{baseUrl}}'],
  path: p.split('/').filter(Boolean),
});
const keyHeader = { key: 'X-API-Key', value: '{{apiKey}}' };
const json = (o) => JSON.stringify(o, null, 2);

const get = (name, p, withKey, description) => ({
  name,
  request: { method: 'GET', header: withKey ? [keyHeader] : [], url: url(p), description },
});
const post = (name, payload, description) => ({
  name,
  event: [{ listen: 'test', script: { type: 'text/javascript', exec: postTestLines } }],
  request: {
    method: 'POST',
    header: [keyHeader, { key: 'Content-Type', value: 'application/json' }],
    body: { mode: 'raw', raw: json(payload), options: { raw: { language: 'json' } } },
    url: url('/api/public/v1/submissions'),
    description,
  },
});

const collection = {
  info: {
    name: 'TransferHub Partner API - Pacific Ridge University demo',
    description: 'Generated by docs/demo-data/build-postman.js from pacific-ridge-catalogue.json. Set the apiKey collection variable to the partner key issued for university code PRU.',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [
    { key: 'baseUrl', value: 'https://transferhub.wcubeprojects.in' },
    { key: 'apiKey', value: 'th_live_PASTE_YOUR_KEY' },
    { key: 'reference', value: '' },
  ],
  item: [
    get('Format guide (no key)', '/api/public/v1/format', false, 'Field reference for every entity type. No API key needed.'),
    get('Who am I (check key)', '/api/public/v1/me', true, 'Confirms the key works and shows the university it is scoped to.'),
    post('POST full catalogue (1 university, 10 programs, 50 courses)', data, 'Everything in one submission.'),
    {
      name: 'Step by step',
      item: [
        post('1 University only', { note: 'Step 1 - university', universities: data.universities }, 'Step 1 of the staged demo.'),
        post('2 Programs only', { note: 'Step 2 - programs', programs: data.programs }, 'Step 2. Programs reference the university code PRU.'),
        post('3 Courses with topics only', { note: 'Step 3 - courses with topics', courses: data.courses }, 'Step 3. Courses link to programs by programName and carry syllabus topics.'),
      ],
    },
    get('List my submissions', '/api/public/v1/submissions', true, 'All submissions made with this key.'),
    get('Submission detail (per-row outcome)', '/api/public/v1/submissions/{{reference}}', true, 'Uses the reference saved by the last POST.'),
  ],
};

const out = path.join(dir, 'TransferHub-Partner-API.postman_collection.json');
fs.writeFileSync(out, JSON.stringify(collection, null, 2) + '\n');
JSON.parse(fs.readFileSync(out, 'utf8'));
console.log('Wrote ' + path.basename(out) + ' (' + collection.item.length + ' top-level items)');
