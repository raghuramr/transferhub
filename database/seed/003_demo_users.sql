-- ============================================================
-- Seed 003 – Demo users (one per role) + 120 synthetic transfer students
-- ============================================================
-- Consolidated: the 5 named demo accounts (old seed/004) + the 120
-- generated synthetic students (old seed/008), both Users-entity seed
-- data. Passwords are stored as argon2id hashes; see the placeholder
-- note below — real hashes are set by `npm run seed:users` from src/api.
--
--  super_admin@bu.edu  → SuperAdmin123!
--  admin@bu.edu        → Admin12345!
--  faculty.cs@bu.edu   → Faculty123!
--  agency@partner.edu  → Agency1234!
--  student@test.edu    → Student123!
--  student<N>@transferdemo.edu (120 rows) → Student@123!
--
-- Replace the PasswordHash values with real argon2id hashes generated by
-- the API's seed script (npm run seed:users).
-- ============================================================
USE CreditEvalManager;
GO

-- ─── Named demo accounts ─────────────────────────────────────
DECLARE @SuperAdminRoleId INT = (SELECT Id FROM Roles WHERE Name = 'super_admin');
DECLARE @AdminRoleId      INT = (SELECT Id FROM Roles WHERE Name = 'admin');
DECLARE @FacultyRoleId    INT = (SELECT Id FROM Roles WHERE Name = 'faculty');
DECLARE @AgencyRoleId     INT = (SELECT Id FROM Roles WHERE Name = 'agency');
DECLARE @StudentRoleId    INT = (SELECT Id FROM Roles WHERE Name = 'student');
DECLARE @CSDeptId         INT = (SELECT Id FROM Departments WHERE Code = 'CS');
DECLARE @EvalDeptId       INT = (SELECT Id FROM Departments WHERE Code = 'EVAL');

-- Placeholder hash — will be replaced by npm run seed:users
DECLARE @PlaceholderHash NVARCHAR(255) = '$argon2id$v=19$m=65536,t=3,p=4$PLACEHOLDER$PLACEHOLDER';

MERGE Users AS target
USING (VALUES
    (NEWID(), 'super_admin@bu.edu', @PlaceholderHash, 'System',    'Administrator', @SuperAdminRoleId, @EvalDeptId, NULL, NULL, 1),
    (NEWID(), 'admin@bu.edu',       @PlaceholderHash, 'Credit',    'Evaluator',     @AdminRoleId,      @EvalDeptId, NULL, NULL, 1),
    (NEWID(), 'faculty.cs@bu.edu',  @PlaceholderHash, 'Dr. Jane',  'Lee',           @FacultyRoleId,    @CSDeptId,   NULL, NULL, 1),
    (NEWID(), 'agency@partner.edu', @PlaceholderHash, 'Transfer',  'Agency',        @AgencyRoleId,     NULL,        NULL, 'BU Transfer Partners', 1),
    (NEWID(), 'student@test.edu',   @PlaceholderHash, 'Maya',      'Rivera',        @StudentRoleId,    NULL,        'BU-SYN-001', NULL, 1)
) AS source(Id, Email, PasswordHash, FirstName, LastName, RoleId, DepartmentId, StudentId, AgencyName, IsActive)
ON target.Email = source.Email
WHEN NOT MATCHED THEN
    INSERT (Id, Email, PasswordHash, FirstName, LastName, RoleId, DepartmentId, StudentId, AgencyName, IsActive, MustChangePass)
    VALUES (source.Id, source.Email, source.PasswordHash, source.FirstName, source.LastName,
            source.RoleId, source.DepartmentId, source.StudentId, source.AgencyName, source.IsActive, 1);
GO

-- Student profile for Maya Rivera
INSERT INTO StudentProfiles (UserId, ProgramArea, AdmissionYear, DeadlineDate)
SELECT u.Id, 'Computer Science', 2026, DATEADD(YEAR, 1, GETUTCDATE())
FROM Users u WHERE u.Email = 'student@test.edu'
  AND NOT EXISTS (SELECT 1 FROM StudentProfiles sp WHERE sp.UserId = u.Id);
GO

PRINT 'Demo users seeded. Run ''npm run seed:users'' from src/api to set real password hashes.';
GO

-- ─── 120 synthetic transfer students ──────────────────────────
DECLARE @StudentRoleId2 INT = (SELECT Id FROM Roles WHERE Name = 'student');
DECLARE @PlaceholderHash2 NVARCHAR(255) = '$argon2id$v=19$m=65536,t=3,p=4$PLACEHOLDER$PLACEHOLDER';

IF OBJECT_ID('tempdb..#Gen') IS NOT NULL DROP TABLE #Gen;

;WITH Tally AS (
    SELECT TOP (120) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS N
    FROM sys.all_objects a CROSS JOIN sys.all_objects b
),
FirstNames AS (
    SELECT Name, ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS rn FROM (VALUES
        ('Maya'),('Liam'),('Olivia'),('Noah'),('Emma'),('Ava'),('Ethan'),('Sophia'),
        ('Mason'),('Isabella'),('Lucas'),('Mia'),('Jacob'),('Amelia'),('Aiden'),('Harper'),
        ('Elijah'),('Evelyn'),('James'),('Abigail'),('Benjamin'),('Emily'),('Logan'),('Ella'),
        ('Alexander'),('Scarlett'),('Jackson'),('Grace'),('Daniel'),('Chloe')
    ) AS f(Name)
),
LastNames AS (
    SELECT Name, ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS rn FROM (VALUES
        ('Rivera'),('Chen'),('Patel'),('Kim'),('Garcia'),('Nguyen'),('Smith'),('Johnson'),
        ('Brown'),('Davis'),('Martinez'),('Lopez'),('Wilson'),('Anderson'),('Taylor'),('Thomas'),
        ('Moore'),('Jackson'),('Martin'),('Lee')
    ) AS l(Name)
),
Programs5 AS (
    SELECT Area, ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS rn
    FROM (VALUES ('Computer Science'),('Economics'),('Psychology'),('Biology'),('Mathematics')) AS p(Area)
)
SELECT
    t.N,
    CONCAT('student', t.N, '@transferdemo.edu') AS Email,
    fn.Name AS FirstName,
    ln.Name AS LastName,
    pr.Area AS ProgramArea,
    2022 + ((t.N - 1) % 4) AS AdmissionYear,
    CONCAT('BU-SYN-', FORMAT(t.N + 1, '000')) AS StudentId
INTO #Gen
FROM Tally t
JOIN FirstNames fn ON fn.rn = ((t.N - 1) % 30) + 1
JOIN LastNames ln  ON ln.rn = ((t.N * 7 - 1) % 20) + 1
JOIN Programs5 pr  ON pr.rn = ((t.N - 1) % 5) + 1;

MERGE Users AS target
USING #Gen AS source
ON target.Email = source.Email
WHEN NOT MATCHED THEN
    INSERT (Id, Email, PasswordHash, FirstName, LastName, RoleId, DepartmentId, StudentId, AgencyName, IsActive, MustChangePass)
    VALUES (NEWID(), source.Email, @PlaceholderHash2, source.FirstName, source.LastName,
            @StudentRoleId2, NULL, source.StudentId, NULL, 1, 1);
GO

INSERT INTO StudentProfiles (UserId, ProgramArea, AdmissionYear, DeadlineDate)
SELECT u.Id, g.ProgramArea, g.AdmissionYear, DATEADD(YEAR, 1, GETUTCDATE())
FROM Users u
JOIN #Gen g ON g.Email = u.Email
WHERE NOT EXISTS (SELECT 1 FROM StudentProfiles sp WHERE sp.UserId = u.Id);
GO

DROP TABLE #Gen;
GO

PRINT '120 synthetic students seeded. Run ''npm run seed:users'' to set their password hash (Student@123!).';
GO
